let current = 'ar';

export function detectLanguage() {
  try {
    const saved = localStorage.getItem('voxmorph.lang');
    if (saved && STRINGS[saved]) return saved;
  } catch { /* ignore */ }
  const nav = (navigator.language || 'en').toLowerCase();
  return nav.startsWith('ar') ? 'ar' : 'en';
}

export function setLanguage(lang) {
  current = STRINGS[lang] ? lang : 'en';
  try { localStorage.setItem('voxmorph.lang', current); } catch { /* ignore */ }
  document.documentElement.lang = current;
  document.documentElement.dir = STRINGS[current].dir;
  applyI18n();
}

export function getLanguage() { return current; }

export function t(key) {
  const s = STRINGS[current][key];
  return s === undefined ? (STRINGS.en[key] ?? key) : s;
}

export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
}

export function formatTime(sec) {
  if (!Number.isFinite(sec) || sec < 0) sec = 0;
  const m = Math.floor(sec / 60), s = Math.floor(sec % 60), d = Math.floor((sec % 1) * 10);
  return `${m}:${String(s).padStart(2, '0')}.${d}`;
}
